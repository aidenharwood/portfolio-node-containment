import { mkdirSync, writeFileSync } from 'node:fs';
import { findContentIssues, GAME_CONTENT } from '../packages/shared/src/index.ts';
import { auditDistrict, auditSeams, type AuditFinding, type AuditKind } from '../packages/shared/src/world/audit.ts';

const REPORT = new URL('../docs/audits/2026-11-12-map-audit.md', import.meta.url);
const KINDS: readonly AuditKind[] = ['issue', 'empty-room', 'density', 'dark-room', 'dead-end', 'people', 'seam'];
const VIEWER = 'http://localhost:5173/editor.html';

const messages = findContentIssues(GAME_CONTENT);
const seams = auditSeams(GAME_CONTENT);
const districts = [...GAME_CONTENT.districts.values()].sort((a, b) => a.name.localeCompare(b.name));
const byDistrict = new Map<string, AuditFinding[]>(districts.map((district) => [district.id, [...auditDistrict(GAME_CONTENT, district.id, undefined, messages), ...seams.filter((seam) => seam.districtId === district.id)]]));

const link = (finding: AuditFinding): string => {
  const focus = finding.tile ? `&focus=${finding.tile.x},${finding.tile.y}` : '';
  const room = finding.room ? `&room=${finding.room}` : '';
  return `${VIEWER}?district=${finding.districtId}${room}${focus}`;
};

const lines: string[] = ['# Map audit', '', `Generated by \`npm run audit\` on ${new Date().toISOString().slice(0, 10)}.`, '', '## Summary', ''];
lines.push(`| District | ${KINDS.join(' | ')} |`, `| --- | ${KINDS.map(() => '---').join(' | ')} |`);
for (const district of districts) {
  const findings = byDistrict.get(district.id) ?? [];
  lines.push(`| ${district.name} | ${KINDS.map((kind) => findings.filter((finding) => finding.kind === kind).length || '').join(' | ')} |`);
}
lines.push('');
for (const district of districts) {
  const findings = byDistrict.get(district.id) ?? [];
  lines.push(`## ${district.name} (\`${district.id}\`)`, '');
  if (findings.length === 0) lines.push('No findings.', '');
  for (const kind of KINDS) {
    const ofKind = findings.filter((finding) => finding.kind === kind);
    if (ofKind.length === 0) continue;
    lines.push(`**${kind}**`, '');
    for (const finding of ofKind) lines.push(`- ${finding.message} ([view](${link(finding)}))`);
    lines.push('');
  }
}

mkdirSync(new URL('.', REPORT), { recursive: true });
writeFileSync(REPORT, `${lines.join('\n').trimEnd()}\n`);
const totals = KINDS.map((kind) => `${kind} ${[...byDistrict.values()].flat().filter((finding) => finding.kind === kind).length}`);
console.log(`wrote docs/audits/2026-11-12-map-audit.md — ${totals.join(', ')}`);
